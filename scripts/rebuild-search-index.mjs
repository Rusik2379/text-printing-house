import fs from 'node:fs/promises';
import path from 'node:path';
import { JSDOM } from 'jsdom';
const root = path.resolve(import.meta.dirname, '..');
const entries = [],
  seen = new Set();
let aliases = new Map();
try {
  const raw = await fs.readFile(path.join(root, 'site-search-index.js'), 'utf8');
  const data = JSON.parse(
    raw
      .slice(raw.indexOf('window.TEXT_SITE_INDEX=') + 23)
      .trim()
      .replace(/;$/, ''),
  );
  aliases = new Map(data.map((d) => [d.u, d.a || '']));
} catch {}
async function walk(dir) {
  const out = [];
  for (const e of await fs.readdir(dir, { withFileTypes: true })) {
    if (e.name.startsWith('.') || ['node_modules', 'tests', 'scripts', 'deploy'].includes(e.name))
      continue;
    const p = path.join(dir, e.name);
    if (e.isDirectory()) out.push(...(await walk(p)));
    else if (e.name === 'index.html') out.push(p);
  }
  return out;
}
for (const file of await walk(root)) {
  const relative = path.relative(root, file).replaceAll('\\', '/'),
    route = relative === 'index.html' ? '' : relative.replace(/index\.html$/, '');
  if (route === 'poisk/' || route.startsWith('cities/')) continue;
  const dom = new JSDOM(await fs.readFile(file, 'utf8')),
    d = dom.window.document,
    main = d.querySelector('main'),
    h = d.querySelector('h1');
  if (!main || !h || d.querySelector('meta[name="robots"]')?.content.includes('noindex')) {
    dom.window.close();
    continue;
  }
  const kind =
    route.startsWith('company/article/') && route !== 'company/article/'
      ? 'Статья'
      : /^(kopitsentr|proektnaya-dokumentatsiya|listovaya-poligrafiya|nakleyki-i-stikery|shirokiy-format|uv-pechat-i-rezka)\//.test(
            route,
          )
        ? 'Услуга'
        : /^(guide|requirements|materials|equipment)\//.test(route)
          ? 'Справочник'
          : 'Информация';
  const text = (el) => {
    if (!el) return '';
    const walker = d.createTreeWalker(el, 4),
      parts = [];
    while (walker.nextNode()) parts.push(walker.currentNode.textContent);
    return parts.join(' ').replace(/\s+/g, ' ').trim();
  };
  for (const details of main.querySelectorAll('details')) {
    const summary = details.querySelector('summary');
    if (!summary || details.closest('#federal-order')) continue;
    const q = text(summary),
      key = route + '|' + q;
    if (q.length < 9 || seen.has(key)) continue;
    seen.add(key);
    entries.push({
      t: q,
      d: text(details).slice(q.length).trim().slice(0, 250),
      k: 'Вопросы и ответы',
      u: route + (details.id ? '#' + details.id : main.querySelector('#faq') ? '#faq' : ''),
      x: text(details).slice(0, 2000),
    });
  }
  for (const el of main.querySelectorAll(
    'script,style,nav,footer,aside,[aria-hidden="true"],#federal-order',
  ))
    el.remove();
  entries.push({
    t: text(h),
    d: d.querySelector('meta[name="description"]')?.content || '',
    k: kind,
    u: route,
    x: text(main).slice(0, 7500),
    a: aliases.get(route) || '',
  });
  dom.window.close();
}
const faq = JSON.parse(await fs.readFile(path.join(root, 'company-faq.json'), 'utf8'));
for (const group of faq.groups || [])
  for (const q of group.questions || []) {
    const key = 'company/vopros-otvet/|' + q.question;
    if (seen.has(key)) continue;
    seen.add(key);
    entries.push({
      t: q.question,
      d: q.answer.slice(0, 250),
      k: 'Вопросы и ответы',
      u: 'company/vopros-otvet/#question-' + q.id,
      x: q.answer.slice(0, 2000),
    });
  }
await fs.writeFile(
  path.join(root, 'site-search-index.js'),
  '/* Generated by scripts/rebuild-search-index.mjs */\nwindow.TEXT_SITE_INDEX=' +
    JSON.stringify(entries) +
    ';\n',
);
console.log(
  'Search index:',
  entries.length,
  'records;',
  entries.filter((d) => d.k === 'Статья').length,
  'articles.',
);
